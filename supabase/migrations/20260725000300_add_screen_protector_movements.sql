create or replace function
  public.primitive_repairs_confirm_screen_protector_addon(
    p_sku text,
    p_request_id text,
    p_units integer default 1,
    p_note text default null
  )
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_inventory
    public.primitive_repairs_screen_protectors%rowtype;

  v_existing
    public.primitive_repairs_screen_protector_movements%rowtype;

  v_movement
    public.primitive_repairs_screen_protector_movements%rowtype;

  v_before integer;
  v_operation_id text;
begin
  p_sku := trim(coalesce(p_sku, ''));
  p_request_id := trim(coalesce(p_request_id, ''));

  if p_sku = '' then
    raise exception 'SKU is required.';
  end if;

  if p_request_id = '' then
    raise exception 'Request ID is required.';
  end if;

  if p_units is null or p_units < 1 or p_units > 100 then
    raise exception 'Units must be between 1 and 100.';
  end if;

  select *
  into v_inventory
  from public.primitive_repairs_screen_protectors
  where sku = p_sku
    and active = true
  for update;

  if not found then
    raise exception 'Active inventory SKU was not found.';
  end if;

  v_operation_id :=
    'confirm:' || p_request_id || ':' || p_sku;

  select *
  into v_existing
  from public.primitive_repairs_screen_protector_movements
  where operation_id = v_operation_id;

  if found then
    return jsonb_build_object(
      'success', true,
      'idempotent', true,
      'inventory', to_jsonb(v_inventory),
      'movement', to_jsonb(v_existing)
    );
  end if;

  if v_inventory.quantity < p_units then
    raise exception
      'Insufficient stock. Available quantity: %.',
      v_inventory.quantity;
  end if;

  v_before := v_inventory.quantity;

  update public.primitive_repairs_screen_protectors
  set
    quantity = quantity - p_units,
    available = (quantity - p_units) > 0
  where id = v_inventory.id
  returning *
  into v_inventory;

  insert into
    public.primitive_repairs_screen_protector_movements (
      inventory_id,
      sku,
      request_id,
      movement_type,
      quantity_delta,
      quantity_before,
      quantity_after,
      operation_id,
      note
    )
  values (
    v_inventory.id,
    p_sku,
    p_request_id,
    'CONFIRM_ADDON',
    -p_units,
    v_before,
    v_inventory.quantity,
    v_operation_id,
    nullif(trim(coalesce(p_note, '')), '')
  )
  returning *
  into v_movement;

  return jsonb_build_object(
    'success', true,
    'idempotent', false,
    'inventory', to_jsonb(v_inventory),
    'movement', to_jsonb(v_movement)
  );
end;
$$;

create or replace function
  public.primitive_repairs_restore_screen_protector_addon(
    p_sku text,
    p_request_id text,
    p_note text default null
  )
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_inventory
    public.primitive_repairs_screen_protectors%rowtype;

  v_confirm
    public.primitive_repairs_screen_protector_movements%rowtype;

  v_existing
    public.primitive_repairs_screen_protector_movements%rowtype;

  v_movement
    public.primitive_repairs_screen_protector_movements%rowtype;

  v_units integer;
  v_before integer;
  v_confirm_operation_id text;
  v_restore_operation_id text;
begin
  p_sku := trim(coalesce(p_sku, ''));
  p_request_id := trim(coalesce(p_request_id, ''));

  if p_sku = '' then
    raise exception 'SKU is required.';
  end if;

  if p_request_id = '' then
    raise exception 'Request ID is required.';
  end if;

  select *
  into v_inventory
  from public.primitive_repairs_screen_protectors
  where sku = p_sku
  for update;

  if not found then
    raise exception 'Inventory SKU was not found.';
  end if;

  v_confirm_operation_id :=
    'confirm:' || p_request_id || ':' || p_sku;

  v_restore_operation_id :=
    'restore:' || p_request_id || ':' || p_sku;

  select *
  into v_existing
  from public.primitive_repairs_screen_protector_movements
  where operation_id = v_restore_operation_id;

  if found then
    return jsonb_build_object(
      'success', true,
      'idempotent', true,
      'inventory', to_jsonb(v_inventory),
      'movement', to_jsonb(v_existing)
    );
  end if;

  select *
  into v_confirm
  from public.primitive_repairs_screen_protector_movements
  where operation_id = v_confirm_operation_id;

  if not found then
    raise exception
      'No confirmed add-on exists for this request and SKU.';
  end if;

  v_units := abs(v_confirm.quantity_delta);
  v_before := v_inventory.quantity;

  update public.primitive_repairs_screen_protectors
  set
    quantity = quantity + v_units,
    available = (quantity + v_units) > 0
  where id = v_inventory.id
  returning *
  into v_inventory;

  insert into
    public.primitive_repairs_screen_protector_movements (
      inventory_id,
      sku,
      request_id,
      movement_type,
      quantity_delta,
      quantity_before,
      quantity_after,
      operation_id,
      note
    )
  values (
    v_inventory.id,
    p_sku,
    p_request_id,
    'RESTORE_ADDON',
    v_units,
    v_before,
    v_inventory.quantity,
    v_restore_operation_id,
    nullif(trim(coalesce(p_note, '')), '')
  )
  returning *
  into v_movement;

  return jsonb_build_object(
    'success', true,
    'idempotent', false,
    'inventory', to_jsonb(v_inventory),
    'movement', to_jsonb(v_movement)
  );
end;
$$;

