create table if not exists
  public.primitive_repairs_screen_protector_movements (
    id bigint generated by default as identity primary key,

    inventory_id bigint not null
      references public.primitive_repairs_screen_protectors(id)
      on delete restrict,

    sku text not null,

    request_id text,

    movement_type text not null
      check (
        movement_type in (
          'CONFIRM_ADDON',
          'RESTORE_ADDON',
          'RESTOCK'
        )
      ),

    quantity_delta integer not null
      check (quantity_delta <> 0),

    quantity_before integer not null
      check (quantity_before >= 0),

    quantity_after integer not null
      check (quantity_after >= 0),

    operation_id text not null unique,

    note text,

    created_at timestamptz not null
      default timezone('utc', now())
  );

create index if not exists
  primitive_repairs_screen_protector_movements_sku_idx
on public.primitive_repairs_screen_protector_movements (
  sku,
  created_at desc
);

create index if not exists
  primitive_repairs_screen_protector_movements_request_idx
on public.primitive_repairs_screen_protector_movements (
  request_id,
  sku
);

alter table
  public.primitive_repairs_screen_protector_movements
enable row level security;

revoke all
