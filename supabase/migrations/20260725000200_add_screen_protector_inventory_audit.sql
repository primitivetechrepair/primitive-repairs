create table if not exists
  public.primitive_repairs_screen_protector_inventory_audit (
    id bigint generated by default as identity primary key,

    inventory_id bigint,

    sku text,

    operation text not null
      check (
        operation in (
          'INSERT',
          'UPDATE',
          'DELETE'
        )
      ),

    old_record jsonb,

    new_record jsonb,

    changed_at timestamptz not null
      default timezone('utc', now())
  );

create index if not exists
  primitive_repairs_screen_protector_audit_sku_idx
on public.primitive_repairs_screen_protector_inventory_audit (
  sku,
  changed_at desc
);

alter table
  public.primitive_repairs_screen_protector_inventory_audit
enable row level security;

revoke all
on table
  public.primitive_repairs_screen_protector_inventory_audit
from anon, authenticated;

create or replace function
  public.primitive_repairs_log_screen_protector_inventory_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into
      public.primitive_repairs_screen_protector_inventory_audit (
        inventory_id,
        sku,
        operation,
        old_record,
        new_record
      )
    values (
      new.id,
      new.sku,
      tg_op,
      null,
      to_jsonb(new)
    );

    return new;
  end if;

  if tg_op = 'UPDATE' then
    insert into
      public.primitive_repairs_screen_protector_inventory_audit (
        inventory_id,
        sku,
        operation,
        old_record,
        new_record
      )
    values (
      new.id,
      new.sku,
      tg_op,
      to_jsonb(old),
      to_jsonb(new)
    );

    return new;
  end if;

  insert into
    public.primitive_repairs_screen_protector_inventory_audit (
      inventory_id,
      sku,
      operation,
      old_record,
      new_record
    )
  values (
    old.id,
    old.sku,
    tg_op,
    to_jsonb(old),
    null
  );

  return old;
end;
$$;

revoke all
on function
  public.primitive_repairs_log_screen_protector_inventory_change()
from public, anon, authenticated;

drop trigger if exists
  primitive_repairs_screen_protector_inventory_audit_trigger
on public.primitive_repairs_screen_protectors;

create trigger
  primitive_repairs_screen_protector_inventory_audit_trigger
after insert or update or delete
on public.primitive_repairs_screen_protectors
for each row
execute function
  public.primitive_repairs_log_screen_protector_inventory_change();