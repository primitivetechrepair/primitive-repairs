create table if not exists public.primitive_repairs_screen_protectors (
  id bigint generated by default as identity primary key,

  brand text not null
    check (length(trim(brand)) > 0),

  model text not null
    check (length(trim(model)) > 0),

  sku text not null unique
    check (length(trim(sku)) > 0),

  name text not null
    default 'Premium Tempered Glass',

  label text not null
    default 'Premium Screen Protector',

  price numeric(10, 2) not null
    default 19.00
    check (price >= 0),

  quantity integer not null
    default 0
    check (quantity >= 0),

  available boolean not null
    default false,

  installed boolean not null
    default true,

  active boolean not null
    default true,

  created_at timestamptz not null
    default timezone('utc', now()),

  updated_at timestamptz not null
    default timezone('utc', now())
);

create unique index if not exists
  primitive_repairs_screen_protectors_brand_model_unique
on public.primitive_repairs_screen_protectors (
  lower(brand),
  lower(model)
);

create or replace function
  public.primitive_repairs_touch_screen_protector_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists
  primitive_repairs_screen_protectors_updated_at
on public.primitive_repairs_screen_protectors;

